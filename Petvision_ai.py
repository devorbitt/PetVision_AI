def delfromdir(pathdir, ratio=0.05):
    alldocs = os.listdir(pathdir)
    leftdocs = int(len(alldocs)*ratio)

    left = set(random.sample(alldocs, leftdocs))

    deleted = 0
    for i in alldocs:
        if i not in left:
            os.remove(os.path.join(pathdir, i))
            deleted += 1

